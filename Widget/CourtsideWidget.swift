import SwiftUI
import WidgetKit

struct ProbeEntry: TimelineEntry {
    let date: Date
    let token: String
}

struct ProbeProvider: TimelineProvider {
    func placeholder(in context: Context) -> ProbeEntry {
        ProbeEntry(date: .now, token: "PREVIEW")
    }
    func getSnapshot(in context: Context, completion: @escaping (ProbeEntry) -> Void) {
        completion(ProbeEntry(date: .now, token: context.isPreview ? "PREVIEW" : "SNAPSHOT"))
    }
    func getTimeline(in context: Context, completion: @escaping (Timeline<ProbeEntry>) -> Void) {
        let now = Date()
        let entry = ProbeEntry(date: now, token: String(UUID().uuidString.prefix(8)))
        completion(Timeline(entries: [entry], policy: .after(now.addingTimeInterval(900))))
    }
}

struct ProbeWidgetView: View {
    let entry: ProbeEntry
    @Environment(\.widgetFamily) private var family

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack {
                Image(systemName: "basketball.fill").foregroundStyle(.orange)
                Text("COURTSIDE").font(.caption.bold())
                Spacer(minLength: 0)
            }
            Text("Widget ready").font(family == .systemSmall ? .headline : .title2.bold())
            Text(entry.date, style: .time).font(.callout.monospacedDigit())
            if family != .systemSmall {
                Text("Native WidgetKit • tap to verify deep link").font(.caption)
                Text("Token: " + entry.token).font(.caption.monospaced()).foregroundStyle(.orange)
            }
            if family == .systemLarge {
                Spacer()
                Text("INSTALLATION CHECK").font(.caption2.bold()).foregroundStyle(.secondary)
                Text("This timestamp is generated by the widget extension. Compare the token with the app after tapping.")
                    .font(.subheadline)
                Text("Diagnostic only · no simulated scores").font(.caption).foregroundStyle(.secondary)
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
        .foregroundStyle(.white)
        .containerBackground(Color(red: 0.06, green: 0.08, blue: 0.12), for: .widget)
        .widgetURL(ProbeLink.make(token: entry.token))
    }
}

@main
struct CourtsideProbeWidget: Widget {
    var body: some WidgetConfiguration {
        StaticConfiguration(kind: "CourtsideProbe", provider: ProbeProvider()) { entry in
            ProbeWidgetView(entry: entry)
        }
        .configurationDisplayName("Courtside Test")
        .description("Verify native widget installation and app deep links.")
        .supportedFamilies([.systemSmall, .systemMedium, .systemLarge])
    }
}
